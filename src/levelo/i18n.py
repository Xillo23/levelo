_current = "en"


def system_language():
    try:
        langid = ctypes.windll.kernel32.GetUserDefaultUILanguage()
        return _LANGID_MAP.get(langid & 0x3FF, "en")
    except Exception:
        return "en"


def set_language(code):
    global _current
    _current = code if code in STRINGS else "en"


def current():
    return _current


def t(key, **fmt):
    s = STRINGS.get(_current, {}).get(key) or STRINGS["en"].get(key, key)
    return s.format(**fmt) if fmt else s
